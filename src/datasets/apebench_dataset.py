"""
APEBench-format dataset loader.

Reads shards generated by `scripts/gen_apebench_data.py`:
  shard_000.npz with keys phi (B, n_hist, *spatial, C), y (B, n_out, *spatial, C),
  params (B, params_dim).

Returns ND tensors in our pipeline's standard layout
`(B, lag=n_hist+n_out, *spatial, C+aux)` where aux channels carry the
loss mask, time embedding, and broadcast params.

For 2D PDEs spatial_shape = (H, W).
For 3D PDEs spatial_shape = (H, W, D).
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader


class APEBenchDataset(Dataset):
    """In-memory APEBench-shard dataset with (B, T, *spatial, C+aux) layout.

    Output sample dict:
        input     : (n_total, *spatial, C+aux)
        target    : (n_total, *spatial, C)
        loss_mask : (n_total,)  — 1 over the future segment, 0 over history
        params    : (params_dim,)
        t         : (n_total,)
    where n_total = n_hist + n_out.
    """

    def __init__(
        self,
        data_dir: str | Path,
        family: str,
        split: str,
        normalize: bool = True,
        normalization_stats: Optional[dict] = None,
        residual_anchor: bool = False,
        subsample_n: Optional[int] = None,
    ) -> None:
        """Args:
          subsample_n: if set and split == 'train', use only the first
            subsample_n trajectories of the train shard.  Used for
            sample-efficiency curves.  Normalization stats are computed on
            the FULL train shard (the model just sees a smaller training
            set; the test/val splits are unchanged).
        """
        self.data_dir = Path(data_dir) / family
        self.family = family
        self.split = split

        self.residual_anchor = residual_anchor
        manifest_path = self.data_dir / "manifest.json"
        self.manifest = json.loads(manifest_path.read_text())
        self.spatial_shape = tuple(self.manifest["spatial_shape"])
        self.spatial_dims = self.manifest["spatial_dims"]
        self.num_channels = self.manifest["num_channels"]
        self.n_hist = self.manifest["n_hist"]
        self.n_out = self.manifest["n_out"]
        self.n_total = self.n_hist + self.n_out
        self.params_dim = self.manifest["params_dim"]

        shard_path = self.data_dir / split / "shard_000.npz"
        if not shard_path.exists():
            raise FileNotFoundError(shard_path)
        data = np.load(shard_path)
        self.phi = data["phi"]                           # (N, n_hist, *spatial, C)
        self.y = data["y"]                                # (N, n_out, *spatial, C)
        self.params = data["params"]                      # (N, params_dim)
        self.t_hist = data["t_hist"]                      # (n_hist,)
        self.t_out = data["t_out"]                        # (n_out,)

        # CRITICAL: compute normalization stats on the FULL train split BEFORE
        # subsampling. The subsample is just for reducing the SGD batch
        # diversity (sample-efficiency curves), but val/test should always
        # see the same normalization regardless of N_train. Recomputing
        # stats on the subsample produces different normalizations per N
        # which makes sample-efficiency comparisons invalid.
        self.normalize = normalize
        if normalize and normalization_stats is None:
            # Compute per-channel stats over the FULL phi+y of this split.
            full = np.concatenate([self.phi, self.y], axis=1)
            axes = tuple(range(full.ndim - 1))
            self.phi_mean = full.mean(axis=axes)
            self.phi_std  = full.std(axis=axes) + 1e-8
            self.y_mean = self.phi_mean.copy()
            self.y_std = self.phi_std.copy()
            self.param_mean = self.params.mean(axis=0)
            self.param_std = self.params.std(axis=0) + 1e-8

        # Sample-efficiency curve support: subsample only the train split.
        # Stats above were already computed on FULL data, so subsampling
        # does NOT change the normalization seen by val/test.
        if subsample_n is not None and split == "train":
            n_avail = self.phi.shape[0]
            n_keep = min(subsample_n, n_avail)
            self.phi = self.phi[:n_keep]
            self.y = self.y[:n_keep]
            self.params = self.params[:n_keep]

        if normalize:
            if normalization_stats is None:
                # stats already computed above on full data
                pass
            else:
                self.phi_mean = normalization_stats["phi_mean"]
                self.phi_std = normalization_stats["phi_std"]
                self.y_mean = normalization_stats["y_mean"]
                self.y_std = normalization_stats["y_std"]
                self.param_mean = normalization_stats["param_mean"]
                self.param_std = normalization_stats["param_std"]
        else:
            self.phi_mean = self.phi_std = None
            self.y_mean = self.y_std = None
            self.param_mean = self.param_std = None

    def get_normalization_stats(self) -> dict:
        return {
            "phi_mean": self.phi_mean, "phi_std": self.phi_std,
            "y_mean": self.y_mean, "y_std": self.y_std,
            "param_mean": self.param_mean, "param_std": self.param_std,
        }

    def __len__(self) -> int:
        return self.phi.shape[0]

    def __getitem__(self, idx: int) -> dict:
        phi = self.phi[idx]                                # (n_hist, *spatial, C)
        y = self.y[idx]                                    # (n_out, *spatial, C)
        params = self.params[idx]                          # (params_dim,)
        if self.normalize:
            phi = (phi - self.phi_mean) / self.phi_std
            y = (y - self.y_mean) / self.y_std
            params_n = (params - self.param_mean) / self.param_std
        else:
            params_n = params

        # Build the time-axis-extended input: history segment + zero-future-placeholder.
        # The input tensor carries the data + mask + time + params channels.
        # Shape: (n_total, *spatial, C + 1 (mask) + 1 (t) + params_dim).
        spatial = self.spatial_shape
        n_total = self.n_total
        C = self.num_channels

        # Anchor (in normalized space): u(t = n_hist - 1), the last visible step.
        # Used by residual_anchor mode to make the cyclic-FFT boundary continuous.
        anchor = phi[-1].astype(np.float32)                # (*spatial, C)

        signal = np.zeros((n_total,) + spatial + (C,), dtype=np.float32)
        signal[:self.n_hist] = phi
        target_raw = np.zeros((n_total,) + spatial + (C,), dtype=np.float32)
        target_raw[:self.n_hist] = phi
        target_raw[self.n_hist:] = y

        if self.residual_anchor:
            # Subtract anchor from history input and from full-trajectory target.
            # Future-segment input stays 0 (= 0 residual); the boundary at t=n_hist-1
            # is r(n_hist-1)=0 -> 0 -> continuous, eliminating the dominant
            # cyclic-FFT spectral artifact.
            signal[:self.n_hist] = phi - anchor
            target = target_raw - anchor                    # (n_total, *spatial, C)
        else:
            target = target_raw

        mask = np.zeros((n_total,) + spatial + (1,), dtype=np.float32)
        mask[:self.n_hist] = 1.0

        t_combined = np.concatenate([self.t_hist, self.t_out])
        t_norm = (t_combined - t_combined.min()) / (t_combined.max() - t_combined.min() + 1e-12)
        t_channel_shape = (n_total,) + (1,) * len(spatial) + (1,)
        t_channel = t_norm.reshape(t_channel_shape)
        t_channel = np.broadcast_to(t_channel, (n_total,) + spatial + (1,)).astype(np.float32)

        param_channel_shape = (1,) + (1,) * len(spatial) + (self.params_dim,)
        param_channel = params_n.reshape(param_channel_shape).astype(np.float32)
        param_channel = np.broadcast_to(param_channel, (n_total,) + spatial + (self.params_dim,))

        input_tensor = np.concatenate([signal, mask, t_channel, param_channel], axis=-1)

        loss_mask = np.zeros(n_total, dtype=np.float32)
        loss_mask[self.n_hist:] = 1.0

        return {
            "input": torch.from_numpy(input_tensor.copy()),
            "target": torch.from_numpy(target.copy()),
            "target_raw": torch.from_numpy(target_raw.copy()),
            "loss_mask": torch.from_numpy(loss_mask.copy()),
            "params": torch.from_numpy(params.astype(np.float32)),
            "t": torch.from_numpy(t_combined.astype(np.float32)),
            "anchor": torch.from_numpy(anchor.copy()),
        }


def create_apebench_dataloaders(
    data_dir: str, family: str, batch_size: int = 8, num_workers: int = 0,
    regime: str = "clean", noise_std: float = 0.0, downsample_factor: int = 1,
    seed: int = 0, residual_anchor: bool = False,
    num_train_samples: Optional[int] = None,
):
    """Create ND APEBench dataloaders, optionally with regime perturbations.

    Regimes (applied on the INPUT only; targets stay clean for honest eval):
      - "clean":     standard data, no modification
      - "lowres":    spatial downsample input by `downsample_factor` (then
                     upsample back to target shape via nearest-neighbor;
                     keeps the input/target shapes matched)
      - "noisy":     add Gaussian noise of std `noise_std * channel_std` to input

    `residual_anchor`: when True, the input data channel and the target
    are presented as r(t) = u(t) - u(t = n_hist - 1).  The history-future
    boundary becomes cyclically continuous, satisfying LEMO's lag-equivariance
    hypothesis without changing the architecture.  Eval-time relL2 is still
    reported in the original space via `target_raw`.
    """
    train_ds = APEBenchDataset(data_dir, family, "train",
                                residual_anchor=residual_anchor,
                                subsample_n=num_train_samples)
    stats = train_ds.get_normalization_stats()
    val_ds = APEBenchDataset(data_dir, family, "val", normalization_stats=stats,
                              residual_anchor=residual_anchor)
    test_ds = APEBenchDataset(data_dir, family, "test", normalization_stats=stats,
                               residual_anchor=residual_anchor)
    if regime != "clean":
        train_ds = _RegimeWrap(train_ds, regime, noise_std, downsample_factor, seed)
        val_ds = _RegimeWrap(val_ds, regime, noise_std, downsample_factor, seed + 1)
        test_ds = _RegimeWrap(test_ds, regime, noise_std, downsample_factor, seed + 2)
    train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True,
                              num_workers=num_workers, pin_memory=True)
    val_loader = DataLoader(val_ds, batch_size=batch_size, shuffle=False,
                            num_workers=num_workers, pin_memory=True)
    test_loader = DataLoader(test_ds, batch_size=batch_size, shuffle=False,
                             num_workers=num_workers, pin_memory=True)
    return train_loader, val_loader, test_loader


class _RegimeWrap(Dataset):
    """Apply low-res / noise perturbations to input only.  Target is unchanged
    so evaluation is on the clean future state — the model has to recover
    the future from a degraded observation of the past."""

    def __init__(self, base, regime, noise_std, downsample_factor, seed):
        self.base = base
        self.regime = regime
        self.noise_std = noise_std
        self.downsample_factor = downsample_factor
        self.spatial_shape = base.spatial_shape
        self.num_channels = base.num_channels
        self.n_hist = base.n_hist
        self.rng = np.random.default_rng(seed)
        # Pre-compute per-channel input std for noise scaling.
        if regime == "noisy":
            full = base.phi.reshape(-1, base.num_channels)
            self.channel_std = full.std(axis=0).reshape(*([1] * (len(self.spatial_shape) + 1)),
                                                         base.num_channels) + 1e-8

    def __len__(self):
        return len(self.base)

    def __getitem__(self, idx):
        sample = self.base[idx]
        # The input layout is (n_total, *spatial, C+aux).  We perturb only the
        # data channels (first `num_channels`) and only over the history segment
        # (first `n_hist` time steps).  Aux channels (mask, t, params) untouched.
        x = sample["input"].numpy().copy()
        nc = self.num_channels
        nh = self.n_hist
        if self.regime == "lowres":
            # Subsample then upsample-nearest along spatial axes for the history segment.
            f = self.downsample_factor
            data = x[:nh, ..., :nc]                                 # (nh, *spatial, C)
            # Build slicing for downsample.
            n_sp = len(self.spatial_shape)
            slc = [slice(None)] + [slice(None, None, f)] * n_sp + [slice(None)]
            ds = data[tuple(slc)]
            # Repeat back up.
            for ax_i in range(n_sp):
                ds = np.repeat(ds, f, axis=1 + ax_i)
            # In case repeat overshoots, trim back.
            tgt_shape = data.shape
            slc_trim = [slice(None)] + [slice(0, s) for s in tgt_shape[1:-1]] + [slice(None)]
            x[:nh, ..., :nc] = ds[tuple(slc_trim)]
        elif self.regime == "noisy":
            noise = self.rng.standard_normal(x[:nh, ..., :nc].shape).astype(np.float32)
            x[:nh, ..., :nc] = x[:nh, ..., :nc] + self.noise_std * self.channel_std * noise
        sample["input"] = torch.from_numpy(x)
        return sample
